#include "pch.h"
#include "DumpController.h"
#include <fstream>
#include <iostream>

namespace EclipseKit::App {

    DumpController::DumpController(const Core::Configuration::GameConfiguration* config,
                                   std::unique_ptr<Core::Interfaces::IDumperEngine> engine,
                                   std::unique_ptr<Core::Interfaces::IOutputFormatter> formatter,
                                   std::unique_ptr<Core::Interfaces::IProgressReporter> progress)
        : config_(config), engine_(std::move(engine)), formatter_(std::move(formatter)), progress_(std::move(progress)) {}

    bool DumpController::Run(const std::string& outputFilePath) {
        if (!engine_ || !formatter_ || !progress_) return false;
        if (!engine_->Initialize()) return false;

        const uint64_t totalTypes = engine_->GetTotalTypeCount();
        progress_->Initialize(totalTypes);

        std::vector<std::string> dumped;
        dumped.reserve(static_cast<size_t>(totalTypes));

        for (uint64_t index = 0; index < totalTypes; ++index) {
            try {
                auto content = engine_->DumpTypeByIndex(index);
                if (!content.empty()) {
                    std::stringstream header;
                    header << "// TypeDefIndex: " << index << "\n";
                    dumped.emplace_back(header.str() + content + "\n");
                }
            } catch (...) {
                // Swallow errors to keep dump going
            }
            progress_->UpdateProgress(index);
        }

        progress_->Finalize();

        // Format and prepend header
        std::string combined = formatter_->FormatOutput(dumped);
        std::stringstream whatever;
        whatever << "// Dump generated by EclipseDumper\n";
        whatever << "// Game: " << config_->GameName << "  Version: " << config_->Version << "\n";
        combined = whatever.str() + combined;

        std::ofstream out(outputFilePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            std::cerr << "FATAL ERROR: Failed to create output file: " << outputFilePath << "\n";
            engine_->Shutdown();
            return false;
        }
        out << combined;
        out.close();

        engine_->Shutdown();
        return true;
    }
}
